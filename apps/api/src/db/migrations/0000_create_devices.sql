CREATE TABLE "devices" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"name" text NOT NULL,
	"room" text NOT NULL,
	"board" text NOT NULL,
	"sensor" text NOT NULL,
	"reporting_interval_s" integer DEFAULT 30 NOT NULL,
	"token_hash" "bytea" NOT NULL,
	"token_rotated_at" timestamp with time zone DEFAULT now() NOT NULL,
	"revoked_at" timestamp with time zone,
	"last_seen_at" timestamp with time zone,
	"last_rssi_dbm" integer,
	"firmware_version" text,
	"uptime_s" integer,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "devices_name_length" CHECK (char_length("devices"."name") between 1 and 60),
	CONSTRAINT "devices_room_length" CHECK (char_length("devices"."room") between 1 and 40),
	CONSTRAINT "devices_board_supported" CHECK ("devices"."board" = 'ESP32'),
	CONSTRAINT "devices_sensor_supported" CHECK ("devices"."sensor" = 'BME280'),
	CONSTRAINT "devices_reporting_interval_range" CHECK ("devices"."reporting_interval_s" between 10 and 3600),
	CONSTRAINT "devices_token_hash_sha256" CHECK (octet_length("devices"."token_hash") = 32),
	CONSTRAINT "devices_rssi_range" CHECK ("devices"."last_rssi_dbm" between -120 and 0),
	CONSTRAINT "devices_uptime_nonnegative" CHECK ("devices"."uptime_s" >= 0)
);
